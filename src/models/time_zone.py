    ASIA_TOKYO = "Asia/Tokyo"
    ASIA_SHANGHAI = "Asia/Shanghai"
    ASIA_DUBAI = "Asia/Dubai"
    AUSTRALIA_SYDNEY = "Australia/Sydney"
